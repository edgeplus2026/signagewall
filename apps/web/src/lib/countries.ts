export type CountryCode = (typeof COUNTRY_CODES)[number]

/** The two we serve from, first in the list — everything else is alphabetical. */
const PINNED: CountryCode[] = ['RS', 'AT']

export interface CountryOption {
  code: string
  name: string
}

/**
 * Codes resolved to names in `locale` and sorted the way that language sorts —
 * `localeCompare` matters here, or Č and Ć land after Z in Serbian.
 */
export function countryOptions(locale: string): CountryOption[] {
  const display = new Intl.DisplayNames([locale], { type: 'region', fallback: 'code' })
  const named = COUNTRY_CODES.map((code) => ({
    code,
    name: display.of(code) ?? code,
  }))
  const rest = named
    .filter((c) => !PINNED.includes(c.code))
    .sort((a, b) => a.name.localeCompare(b.name, locale))
  const pinned = PINNED.map((code) => named.find((c) => c.code === code)).filter(
    (c) => c !== undefined,
  )
  return [...pinned, ...rest]
}

export function countryName(code: string, locale: string): string {
  return new Intl.DisplayNames([locale], { type: 'region', fallback: 'code' }).of(code) ?? code
}
